#[test]
fn every_listed_import_binds_through_the_loader() {
    let mut b = ImageBuilder::default();
    let text = b.section(SectionBuild::text(&[0u8; 4]));
    b.entry(text);
    for (dll, names) in MANIFEST {
        let mut spec: Vec<&str> = vec![dll];
        spec.extend(names.iter().copied());
        b.imports(&spec);
    }
    let bytes = b.build().expect("manifest image builds");
    if let Err(e) = Guest::load(&bytes, XlatConfig::default()) {
        panic!("manifest does not bind: {e}");
    }
    let total: usize = MANIFEST.iter().map(|(_, n)| n.len()).sum();
    assert!(
        total > 300,
        "manifest covers the required surface ({total} imports)"
    );
}
